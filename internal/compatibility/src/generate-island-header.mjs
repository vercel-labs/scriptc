#!/usr/bin/env node

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const packageRoot = fileURLToPath(new URL("../", import.meta.url));
const root = fileURLToPath(new URL("../../../", import.meta.url));
const manifestPath = `${packageRoot}dynamic-support.json`;
const headerPath = `${root}packages/runtime/src/scr_island_manifest.h`;
const manifest = JSON.parse(readFileSync(manifestPath, "utf8"));

function wrap(text, width = 88) {
  const out = [];
  for (let i = 0; i < text.length; i += width) out.push(text.slice(i, i + width));
  return out;
}

function render() {
  const lines = [
    "/* Generated by @internal/compatibility from dynamic-support.json.",
    " * Do not edit: the manifest is the implementation-owned builtin registry. */",
    "static const struct {",
    "  const char *name;",
    "  const char *exports;",
    "} isl_builtins[] = {",
  ];
  for (const [module, entry] of Object.entries(manifest.modules)) {
    const chunks = wrap(entry.exports.join(","));
    lines.push(`    {\"node:${module}\",`);
    for (let i = 0; i < chunks.length; i++) {
      lines.push(`     \"${chunks[i]}\"${i === chunks.length - 1 ? "}," : ""}`);
    }
  }
  lines.push("};", "");
  return lines.join("\n");
}

const rendered = render();
if (process.argv.includes("--check")) {
  if (readFileSync(headerPath, "utf8") !== rendered) {
    throw new Error("scr_island_manifest.h is stale; run 'pnpm island-manifest'");
  }
  console.log(`island manifest is current (${Object.keys(manifest.modules).length} modules)`);
} else {
  writeFileSync(headerPath, rendered);
  console.log(`wrote packages/runtime/src/scr_island_manifest.h (${Object.keys(manifest.modules).length} modules)`);
}
