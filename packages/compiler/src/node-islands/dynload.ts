/* Runtime-filesystem `require` (SPEC §5.4): a createRequire() require whose
 * specifier the build cannot name loads a file that exists only when the
 * program runs. The native site calls one generated island module, which
 * resolves the specifier from the calling module's place in the shipped
 * tree and loads it through Node's own loader.
 *
 * Both files are generated into the tree only when such a site exists, so
 * every other program's tree is unchanged (SPEC §6). `owned-modules.json`
 * names the modules the program compiled (their build paths, and the tree
 * paths of the placeholders that stand in for them): a run-time require
 * that resolves to one of them throws ERR_SCRIPTC_DUPLICATE_MODULE, a
 * deliberate and loud divergence from Node, which would load a second
 * instance (the limitations page documents it). */

/** The generated module's path inside the tree. */
export const DYNLOAD_MODULE_PATH = ".scriptc/dynload.cjs";

/** The generated duplicate guard's path inside the tree. */
export const DYNLOAD_OWNED_PATH = ".scriptc/owned-modules.json";

/** The island module every runtime-filesystem require calls. `load` takes
 * the calling module's tree path and the computed specifier. */
export function dynloadModuleSource(): string {
  return `"use strict";
/* Generated by scriptc (SPEC §5.4): the runtime-filesystem require of a
 * program that ships Node islands. Do not edit. */
const { createRequire, isBuiltin, registerHooks } = require("node:module");
const { readFileSync, realpathSync, statSync } = require("node:fs");
const { dirname, isAbsolute, join, relative, resolve, sep } = require("node:path");
const { pathToFileURL } = require("node:url");

const root = resolve(__dirname, "..");
const owned = new Set(require("./owned-modules.json"));
let callerDir = root;
// The island host resolves every module to a file inside the shipped tree.
// This load names a file the program did not ship, so it resolves as Node's
// require does. A hook registered later runs first (Node's chaining), and
// the flag scopes the override to the require() calls load() makes.
let loading = false;
registerHooks({
  resolve(specifier, context, nextResolve) {
    if (!loading) return nextResolve(specifier, context);
    if (isBuiltin(specifier) || specifier.startsWith("node:"))
      return nextResolve(specifier, context);
    if (specifier.startsWith("file:")) return { url: specifier, shortCircuit: true };
    if (isAbsolute(specifier) || specifier.startsWith("./") || specifier.startsWith("../")) {
      const file = probe(isAbsolute(specifier) ? specifier : resolve(callerDir, specifier));
      return { url: pathToFileURL(file).href, shortCircuit: true };
    }
    // A bare name: the modules the program ships, as everywhere else.
    return nextResolve(specifier, context);
  },
});

function isFile(path) {
  try {
    return statSync(path).isFile();
  } catch {
    return false;
  }
}

function isDirectory(path) {
  try {
    return statSync(path).isDirectory();
  } catch {
    return false;
  }
}

/* Node's CommonJS file resolution for a path: the file itself, its
 * extensions, then a directory's package.json "main", then its indexes. */
function probe(path) {
  if (isFile(path)) return path;
  for (const extension of [".js", ".json", ".node"])
    if (isFile(path + extension)) return path + extension;
  if (isDirectory(path)) {
    let main;
    try {
      main = JSON.parse(readFileSync(join(path, "package.json"), "utf8")).main;
    } catch {
      main = undefined;
    }
    if (typeof main === "string") {
      try {
        return probe(resolve(path, main));
      } catch {
        /* fall through to the indexes */
      }
    }
    for (const extension of [".js", ".json", ".node"])
      if (isFile(join(path, "index" + extension))) return join(path, "index" + extension);
  }
  const error = new Error("Cannot find module '" + path + "'");
  error.code = "MODULE_NOT_FOUND";
  throw error;
}

/* Load the module \`specifier\` names from the calling module at
 * \`fromTreePath\` (its path inside the tree). */
exports.load = (fromTreePath, specifier) => {
  if (typeof specifier !== "string") {
    const error = new TypeError(
      'The "id" argument must be of type string. Received ' +
        (specifier === null
          ? "null"
          : specifier === undefined
            ? "undefined"
            : "type " + typeof specifier + " (" + String(specifier) + ")"),
    );
    error.code = "ERR_INVALID_ARG_TYPE";
    throw error;
  }
  const from = join(root, fromTreePath);
  callerDir = dirname(from);
  const request = createRequire(from);
  loading = true;
  let file;
  try {
    file = request.resolve(specifier);
  } finally {
    loading = false;
  }
  let real = file;
  try {
    real = realpathSync(file);
  } catch {
    /* the resolved path */
  }
  const inside = relative(root, real).split(sep).join("/");
  const at = inside.startsWith("../") ? real : inside;
  if (owned.has(inside) || owned.has(real)) {
    const error = new Error(
      specifier +
        " resolves to " +
        at +
        ", a module compiled into this program; loading it at run time would create a second instance",
    );
    error.code = "ERR_SCRIPTC_DUPLICATE_MODULE";
    throw error;
  }
  loading = true;
  try {
    return request(specifier);
  } finally {
    loading = false;
  }
};
`;
}

/** The duplicate guard: every module the program compiled, as a build path
 * (an absolute specifier computed from `import.meta.url` names it so) and,
 * for the ones inside the shipped tree, as their tree path. */
export function ownedModulesJson(entries: readonly string[]): string {
  return `${JSON.stringify([...new Set(entries)].sort(), null, 0)}\n`;
}
