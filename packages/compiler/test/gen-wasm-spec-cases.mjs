/* Regenerates wasm-spec-cases.txt: the binary modules of the WebAssembly
 * specification test suite at the feature level the decoder validates
 * (src/wasm/binary.ts), each with the suite's verdict and V8's.
 *
 *   node gen-wasm-spec-cases.mjs --wast2json <wabt>/bin/wast2json \
 *     --spec <WebAssembly/spec at tag wg-2.0>/test/core \
 *     --extended-const <WebAssembly/extended-const>/test/core > wasm-spec-cases.txt
 *
 * Inputs: every .wast of the 2.0 core suite except simd/ (SIMD is outside
 * the translatable set; the decoder only reports it), plus the extended
 * constant expression proposal's global, data and elem tests. Modules given
 * as text for assert_malformed are skipped (they test the text format).
 * Identical modules are kept once, at their first location.
 *
 * Line format: <suite verdict> <V8 verdict> <file>:<line> <base64>, where a
 * verdict is "valid", "invalid" or "malformed" (V8: "valid" or "invalid").
 * The suite's tests are Apache-2.0 licensed (WebAssembly Community Group). */
import { execFileSync } from "node:child_process";
import { mkdtempSync, readFileSync, readdirSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { parseArgs } from "node:util";

const { values } = parseArgs({
  options: {
    wast2json: { type: "string" },
    spec: { type: "string" },
    "extended-const": { type: "string" },
  },
});
const inputs = [];
for (const name of readdirSync(values.spec).sort()) {
  if (name.endsWith(".wast")) inputs.push({ label: name, path: join(values.spec, name) });
}
for (const name of ["global.wast", "data.wast", "elem.wast"]) {
  inputs.push({ label: `extended-const/${name}`, path: join(values["extended-const"], name) });
}
const seen = new Set();
const lines = [
  "# WebAssembly spec test modules for src/wasm/binary.ts; generated by gen-wasm-spec-cases.mjs.",
  "# Sources: WebAssembly/spec wg-2.0 test/core (without simd/) and WebAssembly/extended-const",
  "# test/core global, data and elem, converted with wabt 1.0.37 wast2json (Apache-2.0).",
  "# <suite verdict> <V8 verdict> <file>:<line> <base64>",
];
for (const { label, path } of inputs) {
  const dir = mkdtempSync(join(tmpdir(), "wasm-spec-"));
  try {
    execFileSync(values.wast2json, [path, "-o", join(dir, "x.json")], { stdio: "pipe" });
    const json = JSON.parse(readFileSync(join(dir, "x.json"), "utf8"));
    for (const command of json.commands) {
      let verdict;
      if (["module", "assert_unlinkable", "assert_uninstantiable"].includes(command.type))
        verdict = "valid";
      else if (command.type === "assert_invalid") verdict = "invalid";
      else if (command.type === "assert_malformed") verdict = "malformed";
      else continue;
      if (command.module_type === "text" || !command.filename?.endsWith(".wasm")) continue;
      const bytes = readFileSync(join(dir, command.filename));
      const b64 = bytes.toString("base64");
      if (seen.has(b64)) continue;
      seen.add(b64);
      const v8 = WebAssembly.validate(bytes) ? "valid" : "invalid";
      lines.push(`${verdict} ${v8} ${label}:${command.line} ${b64}`);
    }
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
}
process.stdout.write(`${lines.join("\n")}\n`);
