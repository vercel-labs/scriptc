/* Two class names of equal length that end in the same four characters hash
 * alike in the table's index, so one case holds both branches and their own
 * key tests keep the classes apart. */
class AlphaThing {
  a = 100;
  get read(): string {
    return "AlphaThing";
  }
}
class BravoThing {
  a = 200;
  get read(): string {
    return "BravoThing";
  }
}

class Base {
  get kind(): string {
    return "base";
  }
}
class Derived extends Base {
  get kind(): string {
    return "derived";
  }
}
class FurtherDerived extends Derived {
  extra = 1;
}

