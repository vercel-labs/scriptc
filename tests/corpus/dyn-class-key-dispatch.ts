const keys = ["read", "kind", "a", "missing"];
let sum = 0;
const seen: string[] = [];
for (const key of keys) {
  for (const value of instances) {
    const read = value[key];
    if (read === undefined) seen.push(`${key}:undefined`);
    else if (typeof read === "number") sum += read;
    else seen.push(`${key}:${read}`);
  }
}
console.log(sum, seen.join(","));

