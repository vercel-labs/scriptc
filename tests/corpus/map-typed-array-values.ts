const bytes = new Uint8Array([1, 2, 3]);
const cache = new Map<string, Uint8Array>([["first", bytes]]);
const found = cache.get("first");
if (found) found[1] = 8;
console.log(found === bytes, bytes[1], cache.has("first"), cache.get("absent") === undefined);
const view = bytes.subarray(1);
cache.set("view", view);
console.log(cache.get("view") === view);
for (const [key, value] of cache) console.log(key, value.length, value[0]);
const snapshot = Array.from(cache.values());
cache.delete("first");
cache.clear();
console.log(snapshot[0] === bytes, snapshot[1] === view, snapshot[0][1]);
